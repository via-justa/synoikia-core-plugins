/** One call per locked key, and the literal an approver must type for it against the fake Grafana. */
export interface LockCase {
  key: string;
  request: { method: string; path: string; body?: unknown };
  confirm: string;
}

const lock = (key: string, path: string, confirm: string, body?: unknown): LockCase => ({
  key,
  request: { method: key.split(' ')[0]!, path, ...(body === undefined ? {} : { body }) },
  confirm,
});

